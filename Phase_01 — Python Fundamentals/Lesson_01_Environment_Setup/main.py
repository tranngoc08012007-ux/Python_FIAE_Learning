# My first Python lesson - getting started with the basics

# print() displays output on the screen
print("Hello, World!")
print(2 + 3)  # print() can also display the result of an expression

# Comments are ignored by Python.
# They help explain the purpose or reasoning behind the code.

# Store personal information in variables
name = "Trần Nguyên Ngọc"
birth_year = 2007
job = "Fachinformatiker Anwendungsentwicklung"
city = "Ho Chi Minh City"

# Using variables instead of hardcoded values makes the code easier to update
current_year = 2026
age = current_year - birth_year

# Calculate the remaining time until the Ausbildung starts
ausbildung_year = 2027
years_left = ausbildung_year - current_year

# Display the stored information
print(name)
print(job)
print(city)
print(age)
print(years_left)

# Variables can be reassigned at any time
age = 20
print(age)
